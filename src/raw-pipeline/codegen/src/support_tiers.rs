pub(crate) fn emit_swift(registry: &SupportRegistry, evidence: &Evidence) -> String {
    let build = evidence.build.expect("evidence carries a build identity");
    let mut s = banner("//");
    s.push_str("\nimport Foundation\n\n");
    for (name, cases) in closed_enums() {
        s.push_str(&format!(
            "public enum {name}: String, CaseIterable, Sendable {{\n"
        ));
        for (id, _, _) in &cases {
            s.push_str(&format!("    case {} = \"{}\"\n", camel_case(id), id));
        }
        s.push_str("\n    /// Short label for a badge or a list row.\n");
        s.push_str("    public var label: String {\n        switch self {\n");
        for (id, label, _) in &cases {
            s.push_str(&format!(
                "        case .{}: return \"{}\"\n",
                camel_case(id),
                escape_swift(label)
            ));
        }
        s.push_str("        }\n    }\n\n");
        s.push_str("    /// The one fixed sentence this state explains itself with.\n");
        s.push_str("    public var explanation: String {\n        switch self {\n");
        for (id, _, explanation) in &cases {
            s.push_str(&format!(
                "        case .{}:\n            return \"{}\"\n",
                camel_case(id),
                escape_swift(explanation)
            ));
        }
        s.push_str("        }\n    }\n}\n\n");
    }
    s.push_str("/// Which branch of the profile resolver produced a render.\n");
    s.push_str("public enum ProfileResolution: String, CaseIterable, Sendable {\n");
    for (id, _) in fallback_rows() {
        s.push_str(&format!("    case {} = \"{}\"\n", camel_case(id), id));
    }
    s.push_str("}\n\n");
    s.push_str("/// One camera body Maple holds a physical fixture for.\n");
    s.push_str("public struct SupportedCamera: Sendable {\n");
    s.push_str("    public let key: String\n");
    s.push_str("    public let displayName: String\n");
    s.push_str("    public let fixture: String\n");
    s.push_str("    public let tier: CameraTier\n");
    s.push_str("    public let lens: LensSupport\n");
    s.push_str("    public let resolution: ProfileResolution\n");
    s.push_str("}\n\n");
    s.push_str("public enum CameraSupportRegistry {\n");
    s.push_str(&format!(
        "    public static let schemaVersion: UInt32 = {SUPPORT_TIER_SCHEMA_VERSION}\n"
    ));
    s.push_str(&format!(
        "    public static let pipelineOutputVersion: UInt32 = {}\n",
        build.pipeline_version
    ));
    s.push_str(&format!(
        "    /// Camera bodies the bundled profile table covers. Each is at\n\
         \x20   /// least `.profiled`; the full list is in docs/camera-support.json.\n\
         \x20   public static let bundledModelCount: Int = {}\n\
         \x20   /// The profile data every tier here was computed against.\n\
         \x20   public static let profileBundleFormat: UInt16 = {}\n\
         \x20   public static let profileBundleDigest: String = \"{}\"\n\n",
        registry.bundled_models.len(),
        registry.profile_bundle_format,
        registry.profile_bundle_digest,
    ));
    s.push_str("    /// Every body with a physical fixture — the only bodies that can\n");
    s.push_str("    /// ever reach `.qualified`.\n");
    s.push_str("    public static let fixturedBodies: [SupportedCamera] = [\n");
    for body in &registry.bodies {
        s.push_str("        SupportedCamera(\n");
        s.push_str(&format!(
            "            key: \"{}\",\n",
            escape_swift(body.key)
        ));
        s.push_str(&format!(
            "            displayName: \"{}\",\n",
            escape_swift(body.display_name)
        ));
        s.push_str(&format!("            fixture: \"{}\",\n", body.fixture));
        s.push_str(&format!(
            "            tier: .{},\n",
            camel_case(body.tier.id())
        ));
        s.push_str(&format!(
            "            lens: .{},\n",
            camel_case(body.lens.id())
        ));
        s.push_str(&format!(
            "            resolution: .{}\n",
            camel_case(body.resolution.id())
        ));
        s.push_str("        ),\n");
    }
    s.push_str("    ]\n\n");
    s.push_str("    /// The tier a resolver outcome earns before any measured evidence.\n");
    s.push_str("    public static func tier(for resolution: ProfileResolution) -> CameraTier {\n");
    s.push_str("        switch resolution {\n");
    for (resolution, tier) in fallback_rows() {
        s.push_str(&format!(
            "        case .{}: return .{}\n",
            camel_case(resolution),
            camel_case(tier)
        ));
    }
    s.push_str("        }\n    }\n\n");
    s.push_str("    /// The tier for the file in hand. A measured body keeps its\n");
    s.push_str("    /// promotion only when this file resolved at least as well as the\n");
    s.push_str("    /// measured one did.\n");
    s.push_str(
        "    public static func tier(forKey key: String, resolution: ProfileResolution) \
         -> CameraTier {\n",
    );
    s.push_str("        let resolved = tier(for: resolution)\n");
    s.push_str("        guard let body = fixturedBodies.first(where: { $0.key == key }),\n");
    s.push_str("              resolved >= tier(for: body.resolution) else { return resolved }\n");
    s.push_str("        return body.tier\n");
    s.push_str("    }\n}\n\n");
    s.push_str("extension CameraTier: Comparable {\n");
    s.push_str("    /// Worst to best, matching `raw_core::support_tiers::CameraTier`.\n");
    s.push_str("    private var rank: Int { CameraTier.allCases.firstIndex(of: self) ?? 0 }\n");
    s.push_str(
        "    public static func < (lhs: CameraTier, rhs: CameraTier) -> Bool \
         { lhs.rank < rhs.rank }\n",
    );
    s.push_str("}\n");
    s
}

