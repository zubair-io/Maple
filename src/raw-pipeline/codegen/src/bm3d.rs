use crate::Target;
use raw_core::stages::bm3d::{
    dct_basis, ANCHOR_PEDESTAL, BLOCK, CHROMA_SIGMA_RATIO, GROUP_MAX, HF_K, KW, LAMBDA_HT,
    LUMA_REC2020, SEARCH_HALF, SIGMA_K, STRIDE, T_MATCH_SQ,
};

pub fn emit(target: Target) -> String {
    let mut out = String::from("// GENERATED BY tools/codegen.sh. DO NOT EDIT.\n// Source: raw-core/src/stages/bm3d/mod.rs (#4629).\n");
    for (name, value) in [
        ("BLOCK", BLOCK),
        ("STRIDE", STRIDE),
        ("SEARCH_HALF", SEARCH_HALF),
        ("GROUP_MAX", GROUP_MAX),
    ] {
        out.push_str(&match target {
            Target::Rust => format!("pub const {name}: usize = {value};\n"),
            Target::Wgsl => format!("const BM3D_{name}: u32 = {value}u;\n"),
            _ => panic!("bm3d supports rust / wgsl"),
        });
    }
    if matches!(target, Target::Wgsl) {
        for (name, value) in [
            ("ANCHOR_PEDESTAL", ANCHOR_PEDESTAL),
            ("CHROMA_SIGMA_RATIO", CHROMA_SIGMA_RATIO),
            ("HF_K", HF_K),
            ("SIGMA_K", SIGMA_K),
            ("T_MATCH_SQ", T_MATCH_SQ),
        ] {
            out.push_str(&format!("const BM3D_{name}: f32 = {value:?};\n"));
        }
        for (name, values) in [("LUMA", LUMA_REC2020), ("KW", KW)] {
            out.push_str(&format!(
                "const BM3D_{name}: array<f32, 3> = array<f32, 3>({:?}, {:?}, {:?});\n",
                values[0], values[1], values[2]
            ));
        }
        out.push_str(&format!("const BM3D_LAMBDA_HT: f32 = {LAMBDA_HT:?};\n"));
        out.push_str(&format!(
            "const BM3D_INV_SQRT2: f32 = {:?};\n",
            std::f32::consts::FRAC_1_SQRT_2
        ));
        let values: Vec<_> = dct_basis()
            .iter()
            .flatten()
            .map(|v| format!("{v:?}"))
            .collect();
        out.push_str(&format!(
            "const BM3D_DCT: array<f32, {}> = array<f32, {}>({});\n",
            BLOCK * BLOCK,
            BLOCK * BLOCK,
            values.join(", ")
        ));
    }
    out
}

#[test]
fn filter_constants_and_basis_come_from_the_cpu() {
    let shader = emit(Target::Wgsl);
    assert!(shader.contains(&format!("BM3D_LAMBDA_HT: f32 = {LAMBDA_HT:?};")));
    for value in dct_basis().iter().flatten() {
        assert!(shader.contains(&format!("{value:?}")));
    }
}

#[test]
fn rgb_and_noise_constants_come_from_the_cpu() {
    let shader = emit(Target::Wgsl);
    for (name, value) in [
        ("SIGMA_K", SIGMA_K),
        ("ANCHOR_PEDESTAL", ANCHOR_PEDESTAL),
        ("CHROMA_SIGMA_RATIO", CHROMA_SIGMA_RATIO),
        ("HF_K", HF_K),
        ("T_MATCH_SQ", T_MATCH_SQ),
    ] {
        assert!(shader.contains(&format!("BM3D_{name}: f32 = {value:?};")));
    }
    for value in LUMA_REC2020.into_iter().chain(KW) {
        assert!(shader.contains(&format!("{value:?}")));
    }
}

#[test]
fn both_targets_use_the_cpu_matching_contract() {
    for (name, value) in [
        ("BLOCK", BLOCK),
        ("STRIDE", STRIDE),
        ("SEARCH_HALF", SEARCH_HALF),
        ("GROUP_MAX", GROUP_MAX),
    ] {
        assert!(emit(Target::Rust).contains(&format!("pub const {name}: usize = {value};")));
        assert!(emit(Target::Wgsl).contains(&format!("const BM3D_{name}: u32 = {value}u;")));
    }
}
