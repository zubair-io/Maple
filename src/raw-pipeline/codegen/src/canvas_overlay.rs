//! The canvas overlay's primitive tags and uniform capacity (#5715), shared by
//! the CPU rasterizer and the GPU overlay pass.
use crate::Target;
use raw_core::canvas::{
    OVERLAY_CAPACITY, OVERLAY_KIND_DISC, OVERLAY_KIND_FILL, OVERLAY_KIND_FILL_OUTSIDE,
};

const HEADER: &str = "// Generated by codegen --schema canvas-overlay. Do not edit.\n\n";

fn emit_rust() -> String {
    format!("{HEADER}pub const OVERLAY_CAPACITY: usize = {OVERLAY_CAPACITY};\n")
}

fn emit_wgsl() -> String {
    [
        ("OVERLAY_CAPACITY", OVERLAY_CAPACITY as u32),
        ("OVERLAY_KIND_FILL", OVERLAY_KIND_FILL),
        ("OVERLAY_KIND_FILL_OUTSIDE", OVERLAY_KIND_FILL_OUTSIDE),
        ("OVERLAY_KIND_DISC", OVERLAY_KIND_DISC),
    ]
    .iter()
    .fold(String::from(HEADER), |out, (name, value)| {
        out + &format!("const {name}: u32 = {value}u;\n")
    })
}

pub fn emit(target: Target) -> Option<String> {
    match target {
        Target::Rust => Some(emit_rust()),
        Target::Wgsl => Some(emit_wgsl()),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wgsl_carries_capacity_and_every_drawn_tag() {
        let wgsl = emit_wgsl();
        assert!(wgsl.contains("const OVERLAY_CAPACITY: u32 = 16u;\n"));
        assert!(wgsl.contains("const OVERLAY_KIND_FILL: u32 = 1u;\n"));
        assert!(wgsl.contains("const OVERLAY_KIND_FILL_OUTSIDE: u32 = 2u;\n"));
        assert!(wgsl.contains("const OVERLAY_KIND_DISC: u32 = 3u;\n"));
    }

    #[test]
    fn rust_carries_capacity() {
        assert!(emit_rust().ends_with("pub const OVERLAY_CAPACITY: usize = 16;\n"));
    }
}
