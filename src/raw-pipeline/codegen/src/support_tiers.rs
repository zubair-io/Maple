pub(crate) fn emit_ts(registry: &SupportRegistry, evidence: &Evidence) -> String {
    let build = evidence.build.expect("evidence carries a build identity");
    let mut s = banner("//");
    s.push('\n');
    for (name, cases) in closed_enums() {
        let members: Vec<String> = cases.iter().map(|(id, _, _)| format!("'{id}'")).collect();
        s.push_str(&ts_union(name, &members));
        s.push('\n');
        s.push_str(&format!(
            "export const {}_LABEL: Readonly<Record<{name}, string>> = {{\n",
            screaming(name)
        ));
        for (id, label, _) in &cases {
            s.push_str(&ts_string_prop(2, id, label));
        }
        s.push_str("};\n\n");
        s.push_str(&format!(
            "export const {}_EXPLANATION: Readonly<Record<{name}, string>> = {{\n",
            screaming(name)
        ));
        for (id, _, explanation) in &cases {
            s.push_str(&ts_string_prop(2, id, explanation));
        }
        s.push_str("};\n\n");
    }
    let resolutions: Vec<String> = fallback_rows()
        .iter()
        .map(|(id, _)| format!("'{id}'"))
        .collect();
    s.push_str("/** Which branch of the profile resolver produced a render. */\n");
    s.push_str(&ts_union("ProfileResolution", &resolutions));
    s.push('\n');
    s.push_str("/** The tier a resolver outcome earns before any measured evidence. */\n");
    s.push_str(
        "export const TIER_FOR_RESOLUTION: Readonly<Record<ProfileResolution, CameraTier>> = {\n",
    );
    for (resolution, tier) in fallback_rows() {
        s.push_str(&format!("  {resolution}: '{tier}',\n"));
    }
    s.push_str("};\n\n");
    s.push_str("/** One camera body Maple holds a physical fixture for. */\n");
    s.push_str("export interface SupportedCamera {\n");
    s.push_str("  readonly key: string;\n");
    s.push_str("  readonly displayName: string;\n");
    s.push_str("  readonly fixture: string;\n");
    s.push_str("  readonly tier: CameraTier;\n");
    s.push_str("  readonly lens: LensSupport;\n");
    s.push_str("  readonly resolution: ProfileResolution;\n");
    s.push_str("}\n\n");
    s.push_str("export const CAMERA_SUPPORT_BUILD = {\n");
    s.push_str(&format!(
        "  schemaVersion: {SUPPORT_TIER_SCHEMA_VERSION},\n"
    ));
    s.push_str(&format!(
        "  pipelineOutputVersion: {},\n",
        build.pipeline_version
    ));
    s.push_str(&format!(
        "  bundledModelCount: {},\n",
        registry.bundled_models.len()
    ));
    s.push_str(&format!(
        "  profileBundleFormat: {},\n",
        registry.profile_bundle_format
    ));
    s.push_str(&ts_string_prop(
        2,
        "profileBundleDigest",
        &registry.profile_bundle_digest,
    ));
    s.push_str("} as const;\n\n");
    s.push_str("/**\n");
    s.push_str(" * Every body with a physical fixture — the only bodies that can ever\n");
    s.push_str(" * reach `qualified`.\n");
    s.push_str(" */\n");
    s.push_str("export const FIXTURED_CAMERAS: readonly SupportedCamera[] = [\n");
    for body in &registry.bodies {
        s.push_str("  {\n");
        s.push_str(&ts_string_prop(4, "key", body.key));
        s.push_str(&ts_string_prop(4, "displayName", body.display_name));
        s.push_str(&format!("    fixture: '{}',\n", body.fixture));
        s.push_str(&format!("    tier: '{}',\n", body.tier.id()));
        s.push_str(&format!("    lens: '{}',\n", body.lens.id()));
        s.push_str(&format!("    resolution: '{}',\n", body.resolution.id()));
        s.push_str("  },\n");
    }
    s.push_str("];\n");
    s
}

/// `CameraTier` -> `CAMERA_TIER`.
fn screaming(pascal: &str) -> String {
    let mut out = String::new();
    for (i, ch) in pascal.chars().enumerate() {
        if ch.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.extend(ch.to_uppercase());
    }
    out
}
#[cfg(test)]
mod tests {
    use super::*;
    use crate::support_tiers_summary::test_support::{evidence, registry};

    #[test]
    fn swift_carries_every_tier_and_body() {
        let out = emit_swift(&registry(), &evidence());
        assert!(out.starts_with("// THIS FILE IS GENERATED"));
        for tier in CameraTier::ALL {
            assert!(
                out.contains(&format!("= \"{}\"", tier.id())),
                "{}",
                tier.id()
            );
        }
        for body in &registry().bodies {
            assert!(out.contains(&format!("key: \"{}\"", body.key)));
        }
        assert!(out.contains("public static func tier(for resolution: ProfileResolution)"));
    }

    #[test]
    fn ts_carries_every_tier_and_body() {
        let out = emit_ts(&registry(), &evidence());
        for tier in CameraTier::ALL {
            assert!(out.contains(&format!("  {}: ", tier.id())), "{}", tier.id());
        }
        for body in &registry().bodies {
            assert!(out.contains(&format!("key: '{}'", body.key)));
        }
        assert!(out.contains("CAMERA_TIER_EXPLANATION"));
        assert!(out.contains("LENS_SUPPORT_EXPLANATION"));
    }

    #[test]
    fn ts_strings_switch_quotes_the_way_prettier_does() {
        assert_eq!(ts_string("plain"), "'plain'");
        assert_eq!(ts_string("camera's"), "\"camera's\"");
        assert_eq!(
            ts_string("a \"quoted\" and camera's"),
            "'a \"quoted\" and camera\\'s'"
        );
    }

    #[test]
    fn screaming_case_matches_the_emitted_constant_names() {
        assert_eq!(screaming("CameraTier"), "CAMERA_TIER");
        assert_eq!(screaming("LensSupport"), "LENS_SUPPORT");
    }
}
