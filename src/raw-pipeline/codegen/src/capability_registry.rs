pub(crate) fn emit_swift(registry: &[Capability], evidence: &Evidence) -> String {
    let build = evidence.build.expect("evidence carries a build identity");
    let mut s = banner("//");
    s.push_str("\nimport Foundation\n\n");
    for (name, cases) in closed_enums() {
        s.push_str(&format!(
            "public enum Capability{name}: String, CaseIterable, Sendable {{\n"
        ));
        for id in cases {
            s.push_str(&format!("    case {} = \"{}\"\n", camel_case(id), id));
        }
        s.push_str("}\n\n");
    }
    s.push_str("/// One editor capability and its computed release state.\n");
    s.push_str("public struct CapabilityRecord: Sendable {\n");
    s.push_str("    public let id: String\n");
    s.push_str("    public let title: String\n");
    s.push_str("    public let owner: String\n");
    s.push_str("    public let surfaces: [CapabilitySurface]\n");
    s.push_str("    public let storageAdapters: [CapabilityStorageAdapter]\n");
    s.push_str("    public let assetClasses: [CapabilityAssetClass]\n");
    s.push_str("    public let previewPaths: [CapabilityPreviewPath]\n");
    s.push_str("    public let exportPaths: [CapabilityExportPath]\n");
    s.push_str("    public let fields: [String]\n");
    s.push_str("    public let integration: [CapabilityEvidenceSource]\n");
    s.push_str("    public let qualification: [CapabilityEvidenceSource]\n");
    s.push_str("    public let releaseState: CapabilityReleaseState\n");
    s.push_str("}\n\n");
    s.push_str("/// The registry plus the build the states were computed for.\n");
    s.push_str("public enum CapabilityRegistry {\n");
    s.push_str(&format!(
        "    public static let pipelineOutputVersion: UInt32 = {}\n",
        build.pipeline_version
    ));
    s.push_str(&format!(
        "    public static let schemaVersion: UInt32 = {}\n\n",
        build.schema_version
    ));
    s.push_str("    public static let all: [CapabilityRecord] = [\n");
    for row in rows(registry, evidence) {
        s.push_str("        CapabilityRecord(\n");
        s.push_str(&format!("            id: \"{}\",\n", row.id));
        s.push_str(&format!("            title: \"{}\",\n", row.title));
        s.push_str(&format!("            owner: \"{}\",\n", row.owner));
        s.push_str(&swift_cases("surfaces", &row.surfaces));
        s.push_str(&swift_cases("storageAdapters", &row.storage_adapters));
        s.push_str(&swift_cases("assetClasses", &row.asset_classes));
        s.push_str(&swift_cases("previewPaths", &row.preview_paths));
        s.push_str(&swift_cases("exportPaths", &row.export_paths));
        s.push_str(&swift_strings("fields", &row.fields));
        s.push_str(&swift_cases("integration", &row.integration));
        s.push_str(&swift_cases("qualification", &row.qualification));
        s.push_str(&format!(
            "            releaseState: .{}\n",
            camel_case(row.state.id())
        ));
        s.push_str("        ),\n");
    }
    s.push_str("    ]\n");
    s.push_str("}\n");
    s
}

fn swift_cases(key: &str, ids: &[&str]) -> String {
    let members: Vec<String> = ids
        .iter()
        .map(|id| format!(".{}", camel_case(id)))
        .collect();
    swift_array(key, &members)
}

fn swift_strings(key: &str, values: &[&str]) -> String {
    let members: Vec<String> = values.iter().map(|v| format!("\"{v}\"")).collect();
    swift_array(key, &members)
}

/// An array argument at 12-space indent, shaped the way `swift-format`
/// lints it: a literal that fits in 100 columns stays on one line with no
/// trailing comma; a longer one breaks one element per line, each with a
/// trailing comma.
fn swift_array(key: &str, members: &[String]) -> String {
    let compact = format!("            {key}: [{}],", members.join(", "));
    if compact.len() <= 100 {
        return format!("{compact}\n");
    }
    let mut s = format!("            {key}: [\n");
    for m in members {
        s.push_str(&format!("                {m},\n"));
    }
    s.push_str("            ],\n");
    s
}

