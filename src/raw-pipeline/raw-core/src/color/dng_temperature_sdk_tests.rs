//! #4630: numeric vectors from the independently compiled Adobe SDK
//! dng_temperature.cpp Set_xy_coord, with its inputs rounded to f32.
//! Source: android.googlesource.com/platform/external/dng_sdk/+/refs/heads/main/source/dng_temperature.cpp
//! These points avoid the SDK 1.4 table's differing 325-mired row; this
//! regression changes the interpolation origin, not Maple's table.
use super::xy_to_temp_tint;

#[test]
fn inverse_matches_independent_sdk_vectors() {
    let vectors: [[f32; 4]; 18] = [
        [0.3838279545, 0.2841948271, 2850.00058229, -149.999972428],
        [
            0.4479934871,
            0.4075490534,
            2850.00026714,
            -3.46694376647e-07,
        ],
        [0.5525931716, 0.6086354256, 2850.0001756, 149.999994034],
        [0.3569014966, 0.2738821208, 3750.00376995, -149.999969103],
        [
            0.3920486271,
            0.3834866583,
            3750.00150229,
            -2.07143283309e-05,
        ],
        [0.4474169016, 0.5561499, 3750.00105704, 149.999992462],
        [0.3317653835, 0.2580831051, 5499.96735567, -149.999993431],
        [
            0.3324049115,
            0.3408484161,
            5499.98326189,
            -1.27400630356e-05,
        ],
        [0.333330065, 0.4605805874, 5499.98900471, 149.999993095],
        [0.3235426247, 0.2515083849, 6500.01898299, -149.999966492],
        [
            0.3135279119,
            0.3235340714,
            6500.00952617,
            -7.71069934712e-06,
        ],
        [0.299565345, 0.4239527583, 6500.00591603, 149.999983649],
        [0.3127032518, 0.241643548, 8499.92739773, -150.000009327],
        [0.2908171117, 0.2998214066, 8499.95921999, 1.45074321421e-05],
        [0.2617659271, 0.3770454228, 8499.97175487, 150.000002846],
        [0.3024311364, 0.2312981039, 11999.990903, -150.000030601],
        [
            0.2718083262,
            0.2775730789,
            11999.9960281,
            -2.65001955717e-06,
        ],
        [0.2328940779, 0.3363775015, 11999.9965638, 149.999992152],
    ];
    for [x, y, temperature, tint] in vectors {
        let actual = xy_to_temp_tint(x, y);
        assert!(
            (actual.0 - temperature).abs() < 0.005,
            "{x},{y}: {:?}",
            actual
        );
        assert!(
            (actual.1 - tint).abs() < 0.0001,
            "{x},{y}: {:?} vs tint {tint}",
            actual
        );
    }
}
