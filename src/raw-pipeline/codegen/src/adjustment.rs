//! Adjustment-schema emitters — Swift + TypeScript output for
//! `raw_core::types::ADJUSTMENT_SCHEMA` (#118).
//!
//! Split out of `main.rs` in #366, when the point-curve emit arms pushed
//! that file past CONTRIBUTING.md's 600-line hard budget. `main.rs` keeps
//! the CLI wiring and the shared `camel_case` helper (`ui_tokens.rs` uses
//! it too); everything that knows the adjustment schema lives here.

use raw_core::types::{FieldKind, FieldSpec};
use raw_core::PIPELINE_OUTPUT_VERSION;

use crate::camel_case;

const BANNER_SWIFT: &str = "// THIS FILE IS GENERATED BY tools/codegen.sh. DO NOT EDIT.\n\
     // Source: src/raw-pipeline/raw-core/src/types/adjustment.rs (ADJUSTMENT_SCHEMA)\n\
     // and src/raw-pipeline/raw-core/src/version.rs (PIPELINE_OUTPUT_VERSION).\n";

const BANNER_TS: &str = "// THIS FILE IS GENERATED BY tools/codegen.sh. DO NOT EDIT.\n\
     // Source: src/raw-pipeline/raw-core/src/types/adjustment.rs (ADJUSTMENT_SCHEMA)\n\
     // and src/raw-pipeline/raw-core/src/version.rs (PIPELINE_OUTPUT_VERSION).\n";

/// Render an `f32` schema constant in a stable, deterministic form.
///
/// Used uniformly for `range.0`, `range.1`, and `default_f32`. `{:?}` picks
/// the shortest round-tripping decimal, which is stable across Rust versions
/// for the literals in `ADJUSTMENT_SCHEMA` (they're all small exact decimals
/// like `2000.0`, `-100.0`, `0.5`, `25.0`).
fn f(v: f32) -> String {
    let s = format!("{:?}", v);
    // `{:?}` on f32 always includes a decimal point. Belt-and-braces guard
    // in case that ever changes: append `.0` if no fractional indicator.
    if s.contains('.') || s.contains('e') || s.contains('E') {
        s
    } else {
        format!("{}.0", s)
    }
}

/// Rewrite backtick-wrapped Rust-style snake_case identifiers in a doc string
/// to their target-language camelCase form. Only tokens that exactly match a
/// schema `name` are rewritten — generic snake_case text (e.g. an XMP key
/// fragment like `crs:Sharpness`) is left alone.
///
/// Motivation (PR #463 review): the canonical `ADJUSTMENT_SCHEMA` doc strings
/// reference sibling fields by their Rust snake_case names (e.g. "use
/// `capture_sharpening_sigma`"). Emitting that verbatim into Swift/TS sends
/// platform callers chasing an identifier that does not exist in their
/// language — Swift sees `captureSharpeningSigma`, TS sees
/// `captureSharpeningSigma`. Both targets use camelCase, so a single
/// rewriter covers both.
fn rewrite_doc_identifiers(doc: &str, schema: &[FieldSpec]) -> String {
    let mut out = String::with_capacity(doc.len());
    let bytes = doc.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'`' {
            // Find the closing backtick.
            if let Some(rel_end) = bytes[i + 1..].iter().position(|&b| b == b'`') {
                let end = i + 1 + rel_end;
                let token = &doc[i + 1..end];
                // Only rewrite if the token exactly matches a schema field
                // name (snake_case). Leaves things like `papp:Foo` and
                // `crs:Bar` untouched because they do not appear as schema
                // names.
                if schema.iter().any(|s| s.name == token) {
                    out.push('`');
                    out.push_str(&camel_case(token));
                    out.push('`');
                } else {
                    out.push_str(&doc[i..=end]);
                }
                i = end + 1;
                continue;
            }
        }
        out.push(doc[i..].chars().next().unwrap());
        i += doc[i..].chars().next().unwrap().len_utf8();
    }
    out
}

// -------------------------------------------------------------------------
// Swift
// -------------------------------------------------------------------------

pub(crate) fn emit_swift(schema: &[FieldSpec]) -> String {
    let mut s = String::new();
    s.push_str(BANNER_SWIFT);
    s.push_str("//\n");
    s.push_str("// Emits range constants and a canonical field-name enum for\n");
    s.push_str("// `AdjustmentModel`. The struct itself + defaults + init stay\n");
    s.push_str("// hand-written in `AdjustmentModel.swift`; Apple's defaults\n");
    s.push_str("// match raw-core's canonical values (per #326, sharpen converges\n");
    s.push_str("// to the reference renderer's import baseline: 40 / 1.0 / 25 / 0).\n");
    s.push_str("// Point-curve fields (#366) contribute a `FieldName` case and no\n");
    s.push_str("// range; the `ToneCurve` value type is hand-written in\n");
    s.push_str("// `ToneCurve.swift`.\n\n");
    s.push_str("import Foundation\n\n");

    // FieldName enum — canonical snake_case names from the schema.
    s.push_str("extension AdjustmentModel {\n");
    s.push_str("    /// Canonical field identifiers, snake_case as recorded in\n");
    s.push_str("    /// `raw_core::types::ADJUSTMENT_SCHEMA`. Use these when you need\n");
    s.push_str("    /// a stable string key independent of Swift's camelCase property names.\n");
    s.push_str("    public enum FieldName: String, CaseIterable, Sendable, Hashable {\n");
    for spec in schema {
        // case <camel> = "<snake>"
        let case_ident = camel_case(spec.name);
        s.push_str(&format!(
            "        case {} = \"{}\"\n",
            case_ident, spec.name
        ));
    }
    s.push_str("    }\n\n");

    // Range constants for F32 fields. `Enum` and `ToneCurve` fields have no
    // numeric range — the match is exhaustive (no wildcard arm) so a future
    // FieldKind variant is a compile error here rather than a silent skip.
    s.push_str("    // MARK: - Range constants (canonical, generated)\n\n");
    for spec in schema {
        match spec.kind {
            FieldKind::F32 => {
                let camel = camel_case(spec.name);
                let doc = rewrite_doc_identifiers(spec.doc, schema);
                s.push_str(&format!("    /// {}\n", doc));
                s.push_str(&format!(
                    "    public static let {}Range: ClosedRange<Double> = {}...{}\n",
                    camel,
                    f(spec.range.0),
                    f(spec.range.1),
                ));
            }
            FieldKind::Enum | FieldKind::ToneCurve => {}
        }
    }

    // Pipeline-output version (#1926). Monotonic cache-invalidation salt for
    // the develop pipeline's rendered output; single-sourced from
    // `raw_core::version::PIPELINE_OUTPUT_VERSION`. Rendered-output caches key
    // on it so one bump in raw-core invalidates every stale entry.
    s.push_str("\n    // MARK: - Pipeline-output version (canonical, generated)\n\n");
    s.push_str(
        "    /// Monotonic version of the develop pipeline's rendered output\n\
         \x20   /// (#1926). Bump in `raw_core::version::PIPELINE_OUTPUT_VERSION`\n\
         \x20   /// whenever a change alters the pixels produced for the same\n\
         \x20   /// (RAW, sidecar) input, or silently reinterprets a stored\n\
         \x20   /// AdjustmentModel value without a load-time converter. Fold it\n\
         \x20   /// into every rendered-output cache key so a single bump\n\
         \x20   /// invalidates stale entries across all platforms.\n",
    );
    s.push_str(&format!(
        "    public static let pipelineOutputVersion: UInt32 = {}\n",
        PIPELINE_OUTPUT_VERSION,
    ));

    s.push_str("}\n\n");

    // Copy/paste/sync groups (#944). Top-level type, not nested on
    // `AdjustmentModel`: the selective-paste UI on both platforms needs it
    // independently of any one model instance.
    s.push_str(&crate::adjustment_groups::emit_swift());
    s
}

