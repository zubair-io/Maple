//! Codegen for `raw_core::airport_tokens`: the Airport 2 design system.
//!
//! Swift goes to MapleUI, TypeScript and SCSS to maple-common. The SCSS
//! target emits CSS custom properties: dark on `:root` and on
//! `[data-airport-theme='dark']`, light on `[data-airport-theme='light']`.

use raw_core::airport_tokens::{
    AirportTheme, AIRPORT_INK_STEPS, AIRPORT_MARKER, AIRPORT_MOTION, AIRPORT_PANORAMA,
    AIRPORT_RADIUS, AIRPORT_SPACE, AIRPORT_TARGET, AIRPORT_THEMES, AIRPORT_TYPE,
};

use crate::camel_case;

const BANNER: &str = "// THIS FILE IS GENERATED BY tools/codegen.sh. DO NOT EDIT.\n\
     // Source: src/raw-pipeline/raw-core/src/airport_tokens.rs (Airport 2, docs/design/airport/README.md).\n";

fn theme_colours(t: &AirportTheme) -> [(&'static str, &'static str); 13] {
    [
        ("base", t.base),
        ("side", t.side),
        ("raised", t.raised),
        ("float", t.float),
        ("photo", t.photo),
        ("selected", t.selected),
        ("line", t.line),
        ("ink", t.ink),
        ("button", t.button),
        ("on_button", t.on_button),
        ("active", t.active),
        ("changed", t.changed),
        ("done", t.done),
    ]
}

fn rgb_channels(hex: &str) -> String {
    let channel = |i: usize| u8::from_str_radix(&hex[1 + i * 2..3 + i * 2], 16).unwrap_or(0);
    format!("{} {} {}", channel(0), channel(1), channel(2))
}

fn kebab(snake: &str) -> String {
    snake.replace('_', "-")
}

fn number(v: f64) -> String {
    if v.fract() == 0.0 {
        format!("{}", v as i64)
    } else {
        format!("{v}")
    }
}

pub fn emit_swift() -> String {
    let mut s = String::from(BANNER);
    s.push_str("\nimport Foundation\n\npublic enum AirportTokens {\n");
    s.push_str("    public struct Theme: Sendable {\n");
    for (name, _) in theme_colours(&AIRPORT_THEMES[0]) {
        s.push_str(&format!(
            "        public let {}: String\n",
            camel_case(name)
        ));
    }
    s.push_str("        public let shadow: String\n    }\n\n");
    for t in AIRPORT_THEMES {
        let fields: Vec<String> = theme_colours(t)
            .iter()
            .map(|(n, v)| format!("        {}: \"{}\"", camel_case(n), v))
            .chain(std::iter::once(format!("        shadow: \"{}\"", t.shadow)))
            .collect();
        s.push_str(&format!(
            "    public static let {} = Theme(\n{}\n    )\n\n",
            t.name,
            fields.join(",\n")
        ));
    }
    s.push_str(&format!(
        "    public static let marker = \"{AIRPORT_MARKER}\"\n\n"
    ));
    for (name, alpha) in AIRPORT_INK_STEPS {
        s.push_str(&format!(
            "    public static let {}: Double = {}\n",
            camel_case(name),
            number(*alpha)
        ));
    }
    s.push_str("\n    public struct TypeRole: Sendable {\n");
    s.push_str("        public let family: String\n        public let weight: Int\n        public let size: CGFloat\n");
    s.push_str("        public let lineHeight: CGFloat\n        public let tracking: CGFloat\n        public let uppercase: Bool\n    }\n\n");
    s.push_str("    public enum Typography {\n");
    for r in AIRPORT_TYPE {
        s.push_str(&format!(
            "        public static let {} = TypeRole(family: \"{}\", weight: {}, size: {}, lineHeight: {}, tracking: {}, uppercase: {})\n",
            camel_case(r.name), r.family, r.weight, r.size, r.line_height, number(r.tracking), r.uppercase
        ));
    }
    s.push_str("    }\n\n");
    let space: Vec<String> = AIRPORT_SPACE.iter().map(|v| v.to_string()).collect();
    s.push_str(&format!(
        "    public static let space: [CGFloat] = [{}]\n",
        space.join(", ")
    ));
    s.push_str(&format!(
        "    public static let target: CGFloat = {AIRPORT_TARGET}\n\n    public enum Radius {{\n"
    ));
    for (name, px) in AIRPORT_RADIUS {
        s.push_str(&format!(
            "        public static let {}: CGFloat = {}\n",
            camel_case(name),
            px
        ));
    }
    s.push_str("    }\n\n    public enum Motion {\n");
    for (name, ms, ease) in AIRPORT_MOTION {
        s.push_str(&format!(
            "        public static let {}: (ms: Int, ease: String) = ({}, \"{}\")\n",
            camel_case(name),
            ms,
            ease
        ));
    }
    s.push_str("    }\n\n    public enum Panorama {\n");
    for (name, pt) in AIRPORT_PANORAMA {
        s.push_str(&format!(
            "        public static let {}: CGFloat = {}\n",
            camel_case(name),
            pt
        ));
    }
    s.push_str("    }\n}\n");
    s
}

pub fn emit_ts() -> String {
    let mut s = String::from(BANNER);
    s.push_str("\nexport const AIRPORT_THEMES = {\n");
    for t in AIRPORT_THEMES {
        s.push_str(&format!("  {}: {{\n", t.name));
        for (n, v) in theme_colours(t) {
            s.push_str(&format!("    {}: '{}',\n", camel_case(n), v));
        }
        s.push_str(&format!("    shadow: '{}',\n  }},\n", t.shadow));
    }
    s.push_str("} as const;\n\nexport type AirportThemeName = keyof typeof AIRPORT_THEMES;\n\n");
    s.push_str(&format!(
        "export const AIRPORT_MARKER = '{AIRPORT_MARKER}';\n\n"
    ));
    s.push_str("export const AIRPORT_INK = {\n");
    for (name, alpha) in AIRPORT_INK_STEPS {
        s.push_str(&format!("  {}: {},\n", camel_case(name), number(*alpha)));
    }
    s.push_str("} as const;\n\nexport const AIRPORT_TYPE = {\n");
    for r in AIRPORT_TYPE {
        s.push_str(&format!(
            "  {}: {{\n    family: '{}',\n    weight: {},\n    size: {},\n    lineHeight: {},\n    tracking: {},\n    uppercase: {},\n  }},\n",
            camel_case(r.name), r.family, r.weight, r.size, r.line_height, number(r.tracking), r.uppercase
        ));
    }
    s.push_str("} as const;\n\n");
    let space: Vec<String> = AIRPORT_SPACE.iter().map(|v| v.to_string()).collect();
    s.push_str(&format!(
        "export const AIRPORT_SPACE = [{}] as const;\n\n",
        space.join(", ")
    ));
    s.push_str(&format!(
        "export const AIRPORT_TARGET = {AIRPORT_TARGET};\n\nexport const AIRPORT_RADIUS = {{\n"
    ));
    for (name, px) in AIRPORT_RADIUS {
        s.push_str(&format!("  {}: {},\n", camel_case(name), px));
    }
    s.push_str("} as const;\n\nexport const AIRPORT_MOTION = {\n");
    for (name, ms, ease) in AIRPORT_MOTION {
        s.push_str(&format!(
            "  {}: {{ ms: {}, ease: '{}' }},\n",
            camel_case(name),
            ms,
            ease
        ));
    }
    s.push_str("} as const;\n\nexport const AIRPORT_PANORAMA = {\n");
    for (name, pt) in AIRPORT_PANORAMA {
        s.push_str(&format!("  {}: {},\n", camel_case(name), pt));
    }
    s.push_str("} as const;\n");
    s
}

fn scss_theme(t: &AirportTheme) -> String {
    let mut s = String::new();
    for (n, v) in theme_colours(t) {
        s.push_str(&format!("  --airport-{}: {};\n", kebab(n), v));
    }
    let ink = rgb_channels(t.ink);
    for (name, alpha) in AIRPORT_INK_STEPS {
        s.push_str(&format!(
            "  --airport-{}: rgb({} / {});\n",
            kebab(name),
            ink,
            number(*alpha)
        ));
    }
    s.push_str(&format!("  --airport-shadow: {};\n", t.shadow));
    s
}

pub fn emit_scss() -> String {
    let mut s = String::from(BANNER);
    for (i, t) in AIRPORT_THEMES.iter().enumerate() {
        let selector = if i == 0 {
            format!(":root,\n[data-airport-theme='{}']", t.name)
        } else {
            format!("[data-airport-theme='{}']", t.name)
        };
        s.push_str(&format!("\n{selector} {{\n{}}}\n", scss_theme(t)));
    }
    s.push_str(&format!(
        "\n:root {{\n  --airport-marker: {AIRPORT_MARKER};\n"
    ));
    for r in AIRPORT_TYPE {
        let n = kebab(r.name);
        let family = if r.family == "Lato" {
            "'Lato', -apple-system, 'Helvetica Neue', sans-serif"
        } else {
            "'JetBrains Mono', ui-monospace, monospace"
        };
        s.push_str(&format!(
            "  --airport-{n}-font: {} {}px / {}px {};\n  --airport-{n}-tracking: {}em;\n",
            r.weight,
            r.size,
            r.line_height,
            family,
            number(r.tracking)
        ));
    }
    for (i, v) in AIRPORT_SPACE.iter().enumerate() {
        s.push_str(&format!("  --airport-space-{}: {}px;\n", i + 1, v));
    }
    s.push_str(&format!("  --airport-target: {AIRPORT_TARGET}px;\n"));
    for (name, px) in AIRPORT_RADIUS {
        s.push_str(&format!("  --airport-radius-{}: {}px;\n", kebab(name), px));
    }
    for (name, ms, ease) in AIRPORT_MOTION {
        s.push_str(&format!(
            "  --airport-{}: {}ms {};\n",
            kebab(name),
            ms,
            ease
        ));
    }
    for (name, pt) in AIRPORT_PANORAMA {
        s.push_str(&format!("  --airport-{}: {}px;\n", kebab(name), pt));
    }
    s.push_str("}\n");
    s
}
