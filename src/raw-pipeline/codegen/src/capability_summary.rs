//! Release summaries for the capability registry (#2430): the
//! human-readable `docs/capability-registry.md` and the machine-readable
//! `docs/capability-registry.json`. Both are derived from the same
//! `classify` pass the Swift / TS / C# consumers use, so the four never
//! disagree about a capability's state or why it holds it.
//!
//! Markdown is emitted as headings + lists only (no tables) and JSON is
//! printed by a small prettier-shaped printer, so both files are stable
//! under the repo's `prettier --check` gate without a formatting pass.

use raw_core::capability_registry::{
    classify, Capability, Evidence, EvidenceSource, Finding, ReleaseState,
};

// -------------------------------------------------------------------------
// Markdown
// -------------------------------------------------------------------------

pub(crate) fn emit_md(registry: &[Capability], evidence: &Evidence) -> String {
    let build = evidence.build.expect("evidence carries a build identity");
    let classified: Vec<_> = registry
        .iter()
        .map(|c| (c, classify(c, evidence)))
        .collect();
    let count = |state: ReleaseState| classified.iter().filter(|(_, c)| c.state == state).count();

    let mut s = String::new();
    s.push_str("# Capability registry\n\n");
    s.push_str("<!-- THIS FILE IS GENERATED BY tools/codegen.sh. DO NOT EDIT. -->\n\n");
    s.push_str(
        "Generated from `src/raw-pipeline/raw-core/src/capability_registry/` (the registry, reviewed Rust) and the harness evidence records under `test-fixtures/qualification/` by `codegen --schema capability-registry --target md` (ticket #2430). The `codegen-drift` CI job regenerates this file on every push; a hand edit fails that gate. Release state is computed, never asserted — see `docs/testing.md` § \"Capability registry and qualification evidence\" for the rule and the operator workflow.\n\n",
    );
    s.push_str("## Build\n\n");
    s.push_str(&format!(
        "- Pipeline output version: {}\n",
        build.pipeline_version
    ));
    s.push_str(&format!(
        "- Sidecar schema version: {}\n",
        build.schema_version
    ));
    s.push_str(&format!(
        "- Capabilities: {} ({} released, {} integrated, {} core)\n\n",
        classified.len(),
        count(ReleaseState::Released),
        count(ReleaseState::Integrated),
        count(ReleaseState::Core)
    ));

    s.push_str("## Capabilities\n\n");
    for (cap, c) in &classified {
        s.push_str(&format!("### `{}` — {}\n\n", cap.id, cap.title));
        s.push_str(&format!("- State: **{}**\n", c.state.id()));
        s.push_str(&format!("- Owner: `{}`\n", cap.owner));
        s.push_str(&md_list("Surfaces", cap.surfaces.iter().map(|s| s.id())));
        s.push_str(&md_list(
            "Storage adapters",
            cap.storage_adapters.iter().map(|s| s.id()),
        ));
        s.push_str(&md_list(
            "Asset classes",
            cap.asset_classes.iter().map(|s| s.id()),
        ));
        s.push_str(&md_list(
            "Preview paths",
            cap.preview_paths.iter().map(|s| s.id()),
        ));
        s.push_str(&md_list(
            "Export paths",
            cap.export_paths.iter().map(|s| s.id()),
        ));
        s.push_str(&md_list("Fields", cap.owned_fields().into_iter()));
        s.push_str(&md_findings("Integration evidence", &c.integration));
        s.push_str(&md_findings("Qualification evidence", &c.qualification));
        s.push('\n');
    }

    s.push_str("## Evidence sources\n\n");
    for source in EvidenceSource::ALL {
        s.push_str(&format!("### `{}`\n\n", source.id()));
        s.push_str(&format!("- {}\n", source.description()));
        s.push_str(&md_list("Covers", source.covers().iter().map(|s| s.id())));
        s.push_str(&md_list(
            "Accepted backends",
            source.accepted_backends().iter().copied(),
        ));
        s.push_str(&format!("- Expected cases: {}\n", source.expected_cases()));
        s.push_str(&md_list("Corpus", source.corpus().iter().copied()));
        let status = raw_core::capability_registry::judge(*source, evidence);
        match evidence.records.get(source) {
            Some(r) => s.push_str(&format!(
                "- Record: {} — {} of {} executed, {} failed, {} skipped, on `{}`, pipeline v{}, schema v{}, commit `{}`, recorded {}\n",
                status.describe(),
                r.executed_cases,
                r.expected_cases,
                r.failed_cases,
                r.skipped_cases,
                r.backend,
                r.pipeline_version,
                r.schema_version,
                if r.git_sha.is_empty() { "unknown" } else { &r.git_sha },
                if r.recorded_at.is_empty() { "at an unknown time" } else { &r.recorded_at },
            )),
            None => s.push_str(&format!("- Record: {}\n", status.describe())),
        }
        s.push('\n');
    }
    s.trim_end().to_owned() + "\n"
}

fn md_list<'a>(label: &str, items: impl Iterator<Item = &'a str>) -> String {
    let quoted: Vec<String> = items.map(|i| format!("`{i}`")).collect();
    if quoted.is_empty() {
        format!("- {label}: none\n")
    } else {
        format!("- {label}: {}\n", quoted.join(", "))
    }
}

fn md_findings(label: &str, findings: &[Finding]) -> String {
    if findings.is_empty() {
        return format!("- {label}: none declared\n");
    }
    let mut s = format!("- {label}:\n");
    for f in findings {
        s.push_str(&format!(
            "  - `{}` — {}\n",
            f.source.id(),
            f.status.describe()
        ));
    }
    s
}

