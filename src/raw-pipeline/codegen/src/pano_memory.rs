//! Emit the panorama stitch's memory model (#5835, #5891) for the Apple merge sheet's output sizing.
use raw_core::pano_memory::{
    PanoMemoryCalibration, PANO_MEMORY_APPLE, PANO_MEMORY_SERVER, PANO_PROXY_PIXELS_MAX,
};

const HEADER: &str = "// Generated by codegen --schema pano-memory. Do not edit.\n\n";

fn camel(snake: &str) -> String {
    let mut out = String::with_capacity(snake.len());
    let mut upper = false;
    for ch in snake.chars() {
        if ch == '_' {
            upper = true;
        } else if upper {
            out.push(ch.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    out
}

/// `value` with `_` every three digits, as swift-format's GroupNumericLiterals asks.
fn grouped(value: u64) -> String {
    let digits = value.to_string();
    let mut out = String::with_capacity(digits.len() + digits.len() / 3);
    for (i, ch) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i) % 3 == 0 {
            out.push('_');
        }
        out.push(ch);
    }
    out
}

fn swift_calibration(name: &str, calibration: &PanoMemoryCalibration) -> String {
    let args: Vec<String> = calibration
        .fields()
        .iter()
        .map(|(field, value)| format!("    {}: {}", camel(field), grouped(*value)))
        .collect();
    format!(
        "  public static let {name} = PanoMemoryCalibration(\n{}\n  )\n",
        args.join(",\n")
    )
}

pub fn emit_swift() -> String {
    let fields: String = PANO_MEMORY_APPLE
        .fields()
        .iter()
        .map(|(field, _)| format!("  public let {}: Int\n", camel(field)))
        .collect();
    format!(
        "{HEADER}public struct PanoMemoryCalibration: Sendable, Equatable {{\n{fields}\n{}{}\n  public static let proxyPixelsMax = {}\n}}\n",
        swift_calibration("server", &PANO_MEMORY_SERVER),
        swift_calibration("apple", &PANO_MEMORY_APPLE),
        grouped(PANO_PROXY_PIXELS_MAX),
    )
}
