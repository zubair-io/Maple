//! Camera / lens support-tier emitters (#2440).
//!
//! The Swift and TypeScript consumers of
//! `raw_core::support_tiers::SupportRegistry`, computed against the same
//! evidence records the capability registry reads: the tier vocabulary,
//! its user-facing explanations, the resolver mapping, and the
//! fixtured-body table. The human and machine summaries
//! (`docs/camera-support.md` / `.json`) live in `support_tiers_summary.rs`.
//!
//! Only the fixtured bodies are emitted as rows. The ~1,400 bundled bodies
//! are `Profiled` by construction — the bundle entry *is* the calibration —
//! so shipping 1,400 identical rows into two app bundles would buy nothing
//! a `tierForResolution` call does not already give at render time. The
//! full model list is emitted once, into the JSON summary, where "does
//! Maple know my camera" is actually answerable.

use raw_core::capability_registry::Evidence;
use raw_core::support_tiers::{
    tier_for_profile_source, CameraTier, LensSupport, ProfileResolution, SupportRegistry,
    SUPPORT_TIER_SCHEMA_VERSION,
};

use crate::camel_case;

pub(crate) const BANNER: &str = "THIS FILE IS GENERATED BY tools/codegen.sh. DO NOT EDIT.\n\
     Source: src/raw-pipeline/raw-core/src/support_tiers/ (FIXTURED_BODIES,\n\
     the bundled profile index) and the evidence records under\n\
     test-fixtures/qualification/ (#2440).\n\
     \n\
     A camera tier is COMPUTED, never asserted. The four lower tiers are a\n\
     total function of which branch the profile resolver takes; promotion\n\
     to `qualified` additionally needs every declared qualification suite\n\
     satisfied on the current pipeline + schema version, over the current\n\
     corpus, with executed == expected cases and zero failures or skips.\n\
     See docs/camera-support.md.";

fn banner(prefix: &str) -> String {
    BANNER
        .lines()
        .map(|l| {
            if l.is_empty() {
                format!("{prefix}\n")
            } else {
                format!("{prefix} {l}\n")
            }
        })
        .collect()
}

/// `(enum name, cases as (id, label, explanation))`, in one place so the
/// four targets cannot disagree on membership, order or wording.
pub(crate) fn closed_enums() -> Vec<(
    &'static str,
    Vec<(&'static str, &'static str, &'static str)>,
)> {
    vec![
        (
            "CameraTier",
            CameraTier::ALL
                .iter()
                .map(|t| (t.id(), t.label(), t.explanation()))
                .collect(),
        ),
        (
            "LensSupport",
            LensSupport::ALL
                .iter()
                .map(|l| (l.id(), l.label(), l.explanation()))
                .collect(),
        ),
    ]
}

/// The resolver's fallback order as `(resolution id, tier id)` pairs — the
/// versioned, testable fallback order the ticket asks the registry to
/// publish, so a surface can map a render-time resolution to a tier
/// without reimplementing the ladder.
pub(crate) fn fallback_rows() -> Vec<(&'static str, &'static str)> {
    raw_core::support_tiers::PROFILE_FALLBACK_ORDER
        .iter()
        .chain(std::iter::once(&ProfileResolution::DecodeFailed))
        .map(|r| (r.id(), tier_for_profile_source(*r).id()))
        .collect()
}

fn escape_swift(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// A TS string literal shaped the way `prettier --single-quote` prints it:
/// single quotes normally, double quotes when the text contains an
/// apostrophe and no double quote (prettier picks whichever quote needs
/// fewer escapes).
fn ts_string(s: &str) -> String {
    let escaped = s.replace('\\', "\\\\");
    if escaped.contains('\'') && !escaped.contains('"') {
        format!("\"{escaped}\"")
    } else {
        format!("'{}'", escaped.replace('\'', "\\'"))
    }
}

/// A `key: <string>,` property at `indent` spaces, broken the way prettier
/// breaks it: onto a continuation line, indented two further, when the
/// one-line form would pass 100 columns.
fn ts_string_prop(indent: usize, key: &str, value: &str) -> String {
    let pad = " ".repeat(indent);
    let literal = ts_string(value);
    let compact = format!("{pad}{key}: {literal},");
    if compact.len() <= 100 {
        return format!("{compact}\n");
    }
    format!("{pad}{key}:\n{}{literal},\n", " ".repeat(indent + 2))
}

/// A string-literal union, printed the way prettier does: one line when it
/// fits in 100 columns, otherwise one member per line.
fn ts_union(name: &str, members: &[String]) -> String {
    let compact = format!("export type {name} = {};", members.join(" | "));
    if compact.len() <= 100 {
        return format!("{compact}\n");
    }
    let mut s = format!("export type {name} =\n");
    for (i, m) in members.iter().enumerate() {
        let sep = if i + 1 == members.len() { ";" } else { "" };
        s.push_str(&format!("  | {m}{sep}\n"));
    }
    s
}

