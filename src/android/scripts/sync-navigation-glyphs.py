#!/usr/bin/env python3
"""Export the same bundled Material Symbols Rounded outlines used by MapleUI."""

import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[3]
source = root / "src/apple/Packages/MapleUI/Sources/MapleUI/Resources/MaterialSymbols"
font = TTFont(source / "Rounded.ttf")
names = json.loads((source / "glyphs.json").read_text())
glyphs = font.getGlyphSet()
scale = 24 / font["head"].unitsPerEm
for name in ["folder", "chevron_right", "expand_more"]:
    pen = SVGPathPen(glyphs)
    glyphs[font.getGlyphName(names[name])].draw(
        TransformPen(pen, (scale, 0, 0, -scale, 0, 24))
    )
    target = root / f"src/android/app/src/main/res/drawable/nav_{name}.xml"
    target.write_text(
        "<!-- Generated by scripts/sync-navigation-glyphs.py from MapleUI Rounded.ttf. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
        'android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
        f'    <path android:fillColor="#FFFFFFFF" android:pathData="{pen.getCommands()}" />\n'
        "</vector>\n"
    )
