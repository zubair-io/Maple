//! Emit the maple_id derivation version (#5106) for the device id caches.
use raw_core::id::MAPLE_ID_DERIVATION_VERSION;

const HEADER: &str = "// Generated by codegen --schema maple-id. Do not edit.\n\n";

pub fn emit_swift() -> String {
    format!(
        "{HEADER}public enum MapleIdDerivationVersion {{\n  public static let current = {MAPLE_ID_DERIVATION_VERSION}\n}}\n"
    )
}

pub fn emit_ts() -> String {
    format!("{HEADER}export const MAPLE_ID_DERIVATION_VERSION = {MAPLE_ID_DERIVATION_VERSION};\n")
}
