pub(crate) fn emit_ts(registry: &[Capability], evidence: &Evidence) -> String {
    let build = evidence.build.expect("evidence carries a build identity");
    let mut s = banner("//");
    s.push('\n');
    for (name, cases) in closed_enums() {
        s.push_str(&ts_union(name, &cases));
        s.push('\n');
    }
    s.push_str("/** One editor capability and its computed release state. */\n");
    s.push_str("export interface CapabilityRecord {\n");
    s.push_str("  readonly id: string;\n");
    s.push_str("  readonly title: string;\n");
    s.push_str("  readonly owner: string;\n");
    s.push_str("  readonly surfaces: readonly CapabilitySurface[];\n");
    s.push_str("  readonly storageAdapters: readonly CapabilityStorageAdapter[];\n");
    s.push_str("  readonly assetClasses: readonly CapabilityAssetClass[];\n");
    s.push_str("  readonly previewPaths: readonly CapabilityPreviewPath[];\n");
    s.push_str("  readonly exportPaths: readonly CapabilityExportPath[];\n");
    s.push_str("  readonly fields: readonly string[];\n");
    s.push_str("  readonly integration: readonly CapabilityEvidenceSource[];\n");
    s.push_str("  readonly qualification: readonly CapabilityEvidenceSource[];\n");
    s.push_str("  readonly releaseState: CapabilityReleaseState;\n");
    s.push_str("}\n\n");
    s.push_str("/** The build the release states were computed for. */\n");
    s.push_str("export const CAPABILITY_REGISTRY_BUILD = {\n");
    s.push_str(&format!(
        "  pipelineOutputVersion: {},\n",
        build.pipeline_version
    ));
    s.push_str(&format!("  schemaVersion: {},\n", build.schema_version));
    s.push_str("} as const;\n\n");
    s.push_str("export const CAPABILITY_REGISTRY: readonly CapabilityRecord[] = [\n");
    for row in rows(registry, evidence) {
        s.push_str("  {\n");
        s.push_str(&format!("    id: '{}',\n", row.id));
        s.push_str(&format!(
            "    title: '{}',\n",
            row.title.replace('\'', "\\'")
        ));
        s.push_str(&format!("    owner: '{}',\n", row.owner));
        s.push_str(&ts_array("surfaces", &row.surfaces));
        s.push_str(&ts_array("storageAdapters", &row.storage_adapters));
        s.push_str(&ts_array("assetClasses", &row.asset_classes));
        s.push_str(&ts_array("previewPaths", &row.preview_paths));
        s.push_str(&ts_array("exportPaths", &row.export_paths));
        s.push_str(&ts_array("fields", &row.fields));
        s.push_str(&ts_array("integration", &row.integration));
        s.push_str(&ts_array("qualification", &row.qualification));
        s.push_str(&format!("    releaseState: '{}',\n", row.state.id()));
        s.push_str("  },\n");
    }
    s.push_str("];\n");
    s
}

/// A string-literal union, formatted the way `prettier --print-width 100`
/// prints it: one line when it fits, otherwise one member per line.
fn ts_union(name: &str, cases: &[&str]) -> String {
    let members: Vec<String> = cases.iter().map(|c| format!("'{c}'")).collect();
    let compact = format!("export type Capability{name} = {};", members.join(" | "));
    if compact.len() <= 100 {
        return format!("{compact}\n");
    }
    let mut s = format!("export type Capability{name} =\n");
    for (i, m) in members.iter().enumerate() {
        let sep = if i == members.len() - 1 { ";" } else { "" };
        s.push_str(&format!("  | {m}{sep}\n"));
    }
    s
}

/// A string array property at 4-space indent, formatted the way `prettier
/// --print-width 100` prints it: one line when it fits, otherwise one
/// element per line (prettier never fills string arrays). Hand-replicated
/// so the emitter stays a pure function — the drift gate confirms the two
/// agree.
fn ts_array(key: &str, values: &[&str]) -> String {
    let quoted: Vec<String> = values.iter().map(|v| format!("'{v}'")).collect();
    let compact = format!("    {key}: [{}],", quoted.join(", "));
    if compact.len() <= 100 {
        return format!("{compact}\n");
    }
    let mut s = format!("    {key}: [\n");
    for q in quoted {
        s.push_str(&format!("      {q},\n"));
    }
    s.push_str("    ],\n");
    s
}

