pub(crate) fn emit_cs(registry: &[Capability], evidence: &Evidence) -> String {
    let build = evidence.build.expect("evidence carries a build identity");
    let mut s = banner("//");
    s.push_str("\nusing System.Collections.Generic;\n\n");
    s.push_str("namespace Maple.WinUI.Generated\n{\n");
    for (name, cases) in closed_enums() {
        let members: Vec<String> = cases.iter().map(|id| pascal_case(id)).collect();
        s.push_str(&format!(
            "    public enum Capability{name} {{ {} }}\n",
            members.join(", ")
        ));
    }
    s.push_str(
        "\n    /// <summary>One editor capability and its computed release state.</summary>\n",
    );
    s.push_str("    public sealed record CapabilityRecord(\n");
    s.push_str("        string Id,\n");
    s.push_str("        string Title,\n");
    s.push_str("        string Owner,\n");
    s.push_str("        IReadOnlyList<CapabilitySurface> Surfaces,\n");
    s.push_str("        IReadOnlyList<CapabilityStorageAdapter> StorageAdapters,\n");
    s.push_str("        IReadOnlyList<CapabilityAssetClass> AssetClasses,\n");
    s.push_str("        IReadOnlyList<CapabilityPreviewPath> PreviewPaths,\n");
    s.push_str("        IReadOnlyList<CapabilityExportPath> ExportPaths,\n");
    s.push_str("        IReadOnlyList<string> Fields,\n");
    s.push_str("        IReadOnlyList<CapabilityEvidenceSource> Integration,\n");
    s.push_str("        IReadOnlyList<CapabilityEvidenceSource> Qualification,\n");
    s.push_str("        CapabilityReleaseState ReleaseState);\n\n");
    s.push_str(
        "    /// <summary>The registry plus the build the states were computed for.</summary>\n",
    );
    s.push_str("    public static class CapabilityRegistry\n    {\n");
    s.push_str(&format!(
        "        public const uint PipelineOutputVersion = {};\n",
        build.pipeline_version
    ));
    s.push_str(&format!(
        "        public const uint SchemaVersion = {};\n\n",
        build.schema_version
    ));
    s.push_str("        public static readonly IReadOnlyList<CapabilityRecord> All = new CapabilityRecord[]\n        {\n");
    for row in rows(registry, evidence) {
        s.push_str("            new(\n");
        s.push_str(&format!("                \"{}\",\n", row.id));
        s.push_str(&format!(
            "                \"{}\",\n",
            row.title.replace('"', "\\\"")
        ));
        s.push_str(&format!("                \"{}\",\n", row.owner));
        s.push_str(&cs_enum_array("CapabilitySurface", &row.surfaces));
        s.push_str(&cs_enum_array(
            "CapabilityStorageAdapter",
            &row.storage_adapters,
        ));
        s.push_str(&cs_enum_array("CapabilityAssetClass", &row.asset_classes));
        s.push_str(&cs_enum_array("CapabilityPreviewPath", &row.preview_paths));
        s.push_str(&cs_enum_array("CapabilityExportPath", &row.export_paths));
        s.push_str(&cs_string_array(&row.fields));
        s.push_str(&cs_enum_array("CapabilityEvidenceSource", &row.integration));
        s.push_str(&cs_enum_array(
            "CapabilityEvidenceSource",
            &row.qualification,
        ));
        s.push_str(&format!(
            "                CapabilityReleaseState.{}),\n",
            pascal_case(row.state.id())
        ));
    }
    s.push_str("        };\n    }\n}\n");
    s
}

fn cs_enum_array(ty: &str, ids: &[&str]) -> String {
    let members: Vec<String> = ids
        .iter()
        .map(|id| format!("{ty}.{}", pascal_case(id)))
        .collect();
    format!("                new {ty}[] {{ {} }},\n", members.join(", "))
}

fn cs_string_array(values: &[&str]) -> String {
    let quoted: Vec<String> = values.iter().map(|v| format!("\"{v}\"")).collect();
    format!(
        "                new string[] {{ {} }},\n",
        quoted.join(", ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use raw_core::capability_registry::{BuildIdentity, CAPABILITY_REGISTRY};

    fn no_evidence() -> Evidence {
        Evidence {
            records: Default::default(),
            build: Some(BuildIdentity {
                pipeline_version: 2,
                schema_version: 5,
            }),
            corpus_hashes: Default::default(),
        }
    }

    #[test]
    fn swift_emits_every_capability_with_a_state() {
        let out = emit_swift(CAPABILITY_REGISTRY, &no_evidence());
        assert_eq!(
            out.matches("CapabilityRecord(\n").count(),
            CAPABILITY_REGISTRY.len()
        );
        assert!(out.contains("public enum CapabilitySurface: String, CaseIterable, Sendable {"));
        assert!(out.contains("    case apiFilesystem = \"api_filesystem\"\n"));
        assert!(out.contains("            surfaces: [.apple, .web, .windows],\n"));
        assert!(out.contains("            fields: [],\n"));
        assert!(out.contains("public static let pipelineOutputVersion: UInt32 = 2\n"));
        // No evidence: nothing can leave Core.
        assert_eq!(
            out.matches("releaseState: .core\n").count(),
            CAPABILITY_REGISTRY.len()
        );
    }

    #[test]
    fn ts_emits_unions_interface_and_registry() {
        let out = emit_ts(CAPABILITY_REGISTRY, &no_evidence());
        assert!(out.contains(
            "export type CapabilityReleaseState = 'core' | 'integrated' | 'released';\n"
        ));
        assert!(out.contains("export type CapabilityStorageAdapter =\n  | 'filesystem'\n"));
        assert!(out.contains("export interface CapabilityRecord {"));
        assert!(out.contains("export const CAPABILITY_REGISTRY_BUILD = {\n  pipelineOutputVersion: 2,\n  schemaVersion: 5,\n} as const;"));
        assert_eq!(out.matches("    id: '").count(), CAPABILITY_REGISTRY.len());
        assert!(out.contains("    surfaces: ['apple', 'web', 'windows'],\n"));
        // Every emitted line respects prettier's 100-column print width.
        assert!(
            out.lines().all(|l| l.len() <= 100),
            "a line exceeds 100 columns"
        );
    }

    #[test]
    fn cs_emits_enums_record_and_registry() {
        let out = emit_cs(CAPABILITY_REGISTRY, &no_evidence());
        assert!(out.contains("namespace Maple.WinUI.Generated"));
        assert!(out.contains("public enum CapabilitySurface { Apple, Web, Windows }"));
        assert!(out.contains("public sealed record CapabilityRecord("));
        assert!(out.contains("public const uint PipelineOutputVersion = 2;"));
        assert_eq!(
            out.matches("            new(\n").count(),
            CAPABILITY_REGISTRY.len()
        );
        assert!(
            out.contains("new CapabilityStorageAdapter[] { CapabilityStorageAdapter.ApiFilesystem")
        );
    }

    #[test]
    fn determinism_double_emit_is_identical() {
        let e = no_evidence();
        assert_eq!(
            emit_swift(CAPABILITY_REGISTRY, &e),
            emit_swift(CAPABILITY_REGISTRY, &e)
        );
        assert_eq!(
            emit_ts(CAPABILITY_REGISTRY, &e),
            emit_ts(CAPABILITY_REGISTRY, &e)
        );
        assert_eq!(
            emit_cs(CAPABILITY_REGISTRY, &e),
            emit_cs(CAPABILITY_REGISTRY, &e)
        );
    }
}
