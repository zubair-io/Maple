//! Capability-registry emitters — Swift, TypeScript, and C# consumers of
//! `raw_core::capability_registry::CAPABILITY_REGISTRY` with the release
//! state computed from the evidence records on disk (ticket #2430).
//!
//! Every consumer carries the same facts: the closed enums (surfaces,
//! adapters, asset classes, render paths, evidence sources, release
//! states), one record per capability, and the build identity the states
//! were computed against. The human/machine release summaries live in
//! `capability_summary.rs`.

use raw_core::capability_registry::{
    classify, AssetClass, Capability, Evidence, EvidenceSource, ExportPath, PreviewPath,
    ReleaseState, StorageAdapter, Surface,
};

use crate::camel_case;

const BANNER: &str = "THIS FILE IS GENERATED BY tools/codegen.sh. DO NOT EDIT.\n\
     Source: src/raw-pipeline/raw-core/src/capability_registry/ (CAPABILITY_REGISTRY)\n\
     and the evidence records under test-fixtures/qualification/ (#2430).\n\
     \n\
     Release state is COMPUTED from harness evidence, never asserted: a\n\
     capability reads `released` only when every declared evidence source\n\
     has a record on the current pipeline + schema version, over the\n\
     current corpus, on an accepted backend, with executed == expected\n\
     cases, zero failures, and zero skips. See docs/capability-registry.md.";

fn banner(prefix: &str) -> String {
    BANNER
        .lines()
        .map(|l| {
            if l.is_empty() {
                format!("{prefix}\n")
            } else {
                format!("{prefix} {l}\n")
            }
        })
        .collect()
}

/// `(enum name, every (id) case)` for each closed enum, in one place so the
/// three targets cannot disagree on membership or order.
fn closed_enums() -> Vec<(&'static str, Vec<&'static str>)> {
    vec![
        ("Surface", Surface::ALL.iter().map(|s| s.id()).collect()),
        (
            "StorageAdapter",
            StorageAdapter::ALL.iter().map(|s| s.id()).collect(),
        ),
        (
            "AssetClass",
            AssetClass::ALL.iter().map(|s| s.id()).collect(),
        ),
        (
            "PreviewPath",
            PreviewPath::ALL.iter().map(|s| s.id()).collect(),
        ),
        (
            "ExportPath",
            ExportPath::ALL.iter().map(|s| s.id()).collect(),
        ),
        (
            "EvidenceSource",
            EvidenceSource::ALL.iter().map(|s| s.id()).collect(),
        ),
        ("ReleaseState", vec!["core", "integrated", "released"]),
    ]
}

/// The per-capability facts every target emits, already stringified.
struct Row {
    id: &'static str,
    title: &'static str,
    owner: &'static str,
    surfaces: Vec<&'static str>,
    storage_adapters: Vec<&'static str>,
    asset_classes: Vec<&'static str>,
    preview_paths: Vec<&'static str>,
    export_paths: Vec<&'static str>,
    fields: Vec<&'static str>,
    integration: Vec<&'static str>,
    qualification: Vec<&'static str>,
    state: ReleaseState,
}

fn rows(registry: &[Capability], evidence: &Evidence) -> Vec<Row> {
    registry
        .iter()
        .map(|c| Row {
            id: c.id,
            title: c.title,
            owner: c.owner,
            surfaces: c.surfaces.iter().map(|s| s.id()).collect(),
            storage_adapters: c.storage_adapters.iter().map(|s| s.id()).collect(),
            asset_classes: c.asset_classes.iter().map(|s| s.id()).collect(),
            preview_paths: c.preview_paths.iter().map(|s| s.id()).collect(),
            export_paths: c.export_paths.iter().map(|s| s.id()).collect(),
            fields: c.owned_fields(),
            integration: c.integration.iter().map(|s| s.id()).collect(),
            qualification: c.qualification.iter().map(|s| s.id()).collect(),
            state: classify(c, evidence).state,
        })
        .collect()
}

fn pascal_case(snake: &str) -> String {
    let camel = camel_case(snake);
    let mut chars = camel.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

