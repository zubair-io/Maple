// Maple's Android vectors use the exact paths drawn by Apple and Web (#4623).
import {
  TOOL_ICON_SHAPES,
  TOOL_GLYPH_STROKE_WIDTH,
} from '../../web/projects/maple-common/src/lib/icons/tool-glyph-shapes';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dir, '../app/src/main');
const destination = resolve(root, 'res/drawable');
mkdirSync(destination, { recursive: true });
for (const [name, shapes] of Object.entries(TOOL_ICON_SHAPES)) {
  const paths = shapes.map((shape) => {
    const d =
      shape.kind === 'path'
        ? shape.d
        : shape.kind === 'circle'
          ? `M${shape.cx - shape.r},${shape.cy}a${shape.r},${shape.r} 0,1 0,${shape.r * 2},0a${shape.r},${shape.r} 0,1 0,-${shape.r * 2},0`
          : shape.kind === 'rect'
            ? `M${shape.x + (shape.rx ?? 0)},${shape.y}h${shape.width - 2 * (shape.rx ?? 0)}a${shape.rx ?? 0},${shape.rx ?? 0} 0,0 1,${shape.rx ?? 0},${shape.rx ?? 0}v${shape.height - 2 * (shape.rx ?? 0)}a${shape.rx ?? 0},${shape.rx ?? 0} 0,0 1,-${shape.rx ?? 0},${shape.rx ?? 0}h-${shape.width - 2 * (shape.rx ?? 0)}a${shape.rx ?? 0},${shape.rx ?? 0} 0,0 1,-${shape.rx ?? 0},-${shape.rx ?? 0}v-${shape.height - 2 * (shape.rx ?? 0)}a${shape.rx ?? 0},${shape.rx ?? 0} 0,0 1,${shape.rx ?? 0},-${shape.rx ?? 0}Z`
            : (() => {
                throw new Error(`Unsupported tool shape ${shape.kind}`);
              })();
    return `    <path android:pathData="${d}" android:fillColor="@android:color/transparent" android:strokeColor="#FFFFFFFF" android:strokeWidth="${TOOL_GLYPH_STROKE_WIDTH}" android:strokeLineCap="round" android:strokeLineJoin="round" />`;
  });
  writeFileSync(
    resolve(destination, `${name.replaceAll('-', '_')}.xml`),
    `<!-- Generated by scripts/sync-tool-glyphs.ts. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="20dp" android:height="20dp" android:viewportWidth="16" android:viewportHeight="16">\n${paths.join('\n')}\n</vector>\n`,
  );
}
