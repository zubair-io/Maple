//! Android's Kotlin values and native field access come from the same schema.
use raw_core::types::{FieldKind, ADJUSTMENT_SCHEMA, TRANSFER_XMP_ATTRIBUTES};
use raw_core::ui_tokens::{COLOR_TOKENS, MOTION_TOKENS, RADIUS_TOKENS, SPACING_TOKENS};
use std::{fs, path::Path};

#[derive(Default)]
struct RasterRestrictions(std::collections::BTreeSet<String>);

impl<'ast> syn::visit::Visit<'ast> for RasterRestrictions {
    fn visit_expr_field(&mut self, field: &'ast syn::ExprField) {
        if matches!(&*field.base, syn::Expr::Path(path) if path.path.is_ident("model")) {
            if let syn::Member::Named(name) = &field.member {
                self.0.insert(name.to_string());
            }
        }
        syn::visit::visit_expr_field(self, field);
    }
}

fn raster_restrictions() -> std::collections::BTreeSet<String> {
    use syn::visit::Visit;
    let source = include_str!("../../raw-core/src/pipeline/render/export/raster.rs");
    let file = syn::parse_file(source).expect("raster validator source");
    let validator = file
        .items
        .iter()
        .find_map(|item| match item {
            syn::Item::Fn(function) if function.sig.ident == "validate_raster_adjustments" => {
                Some(function)
            }
            _ => None,
        })
        .expect("canonical raster validator");
    let mut fields = RasterRestrictions::default();
    fields.visit_block(&validator.block);
    fields.0
}

const HEADER: &str = "// Generated by tools/codegen.sh. DO NOT EDIT.\n";

fn write(path: &Path, body: String) -> std::io::Result<()> {
    fs::create_dir_all(path.parent().expect("generated file parent"))?;
    fs::write(path, body)
}

fn main() -> std::io::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let kotlin = root.join("src/android/app/src/main/java/app/justmaple/aperture/generated");
    write_slider_gradients(&root, &kotlin)?;
    write_white_balance_presets(&kotlin)?;
    let mut colors =
        String::from("<!-- Generated by tools/codegen.sh. DO NOT EDIT. -->\n<resources>\n");
    for color in COLOR_TOKENS
        .iter()
        .filter(|color| color.value.starts_with('#'))
    {
        colors.push_str(&format!(
            "    <color name=\"maple_{}\">{}</color>\n",
            color.name, color.value
        ));
    }
    colors.push_str("</resources>\n");
    write(
        &root.join("src/android/app/src/main/res/values/maple-tokens.xml"),
        colors,
    )?;
    let mut tokens =
        format!("{HEADER}package app.justmaple.aperture.generated\n\nobject UiTokens {{\n");
    for color in COLOR_TOKENS {
        tokens.push_str(&format!(
            "    const val {} = \"{}\"\n",
            color.name, color.value
        ));
    }
    for item in MOTION_TOKENS {
        tokens.push_str(&format!("    const val {}Ms = {}\n", item.name, item.ms));
    }
    for item in RADIUS_TOKENS {
        tokens.push_str(&format!(
            "    const val radius_{} = {}f\n",
            item.name, item.px
        ));
    }
    for item in SPACING_TOKENS {
        tokens.push_str(&format!(
            "    const val space_{} = {}f\n",
            item.name, item.px
        ));
    }
    tokens.push_str("}\n");
    write(&kotlin.join("UiTokens.kt"), tokens)?;
    let mut films = format!("{HEADER}package app.justmaple.aperture.generated\n\ndata class FilmLook(val id: String, val label: String)\n\nobject FilmCatalog {{\n    val all = listOf(\n");
    for film in raw_core::film_catalog::FILM_CATALOG {
        let label = serde_json::to_string(film.name)
            .unwrap()
            .replace('$', "\\$");
        films.push_str(&format!("        FilmLook(\"{}\", {label}),\n", film.id));
    }
    films.push_str("    )\n}\n");
    write(&kotlin.join("FilmCatalog.kt"), films)?;
    let scale = match raw_core::types::WbScaleVersion::default() {
        raw_core::types::WbScaleVersion::V1 => 1,
        raw_core::types::WbScaleVersion::V2 => 2,
        raw_core::types::WbScaleVersion::V3 => 3,
        raw_core::types::WbScaleVersion::V4 => 4,
        raw_core::types::WbScaleVersion::V5 => 5,
    };
    let raster_restrictions = raster_restrictions();
    let mut fields = format!("{HEADER}package app.justmaple.aperture.generated\n\ndata class AdjustmentField(val index: Int, val name: String, val minimum: Float, val maximum: Float, val initial: Float, val xmp: String, val rasterSupported: Boolean)\n\nobject AdjustmentFields {{\n    const val whiteBalanceScaleVersion = {scale}\n    val all = listOf(\n");
    let mut native = format!("{HEADER}use raw_core::types::AdjustmentModel;\n\npub fn get(model: &AdjustmentModel, index: usize) -> Option<f32> {{\n    match index {{\n");
    let mut raster_allowed =
        String::from("pub fn raster_allowed(index: usize) -> bool { match index {\n");
    let mut setter = String::from("pub fn set(model: &mut AdjustmentModel, index: usize, value: f32) -> Result<(), String> {\n    let spec = raw_core::types::ADJUSTMENT_SCHEMA.get(index).ok_or(\"Unknown adjustment\")?;\n    if !value.is_finite() || value < spec.range.0 || value > spec.range.1 { return Err(format!(\"{} outside its range\", spec.name)); }\n    match index {\n");
    for (index, field) in ADJUSTMENT_SCHEMA.iter().enumerate() {
        if field.kind != FieldKind::F32 {
            continue;
        }
        let key = TRANSFER_XMP_ATTRIBUTES
            .iter()
            .find(|(name, _)| *name == field.name)
            .and_then(|(_, keys)| keys.first())
            .copied()
            .unwrap_or("");
        let raster_supported = !raster_restrictions.contains(field.name);
        raster_allowed.push_str(&format!("        {index} => {raster_supported},\n"));
        fields.push_str(&format!(
            "        AdjustmentField({index}, \"{}\", {:?}f, {:?}f, {:?}f, \"{key}\", {raster_supported}),\n",
            field.name, field.range.0, field.range.1, field.default_f32
        ));
        native.push_str(&format!("        {index} => Some(model.{}),\n", field.name));
        setter.push_str(&format!(
            "        {index} => model.{} = value,\n",
            field.name
        ));
    }
    fields.push_str("    )\n    val byName = all.associateBy { it.name }\n}\n");
    native.push_str("        _ => None,\n    }\n}\n\n");
    setter.push_str("        _ => return Err(\"Adjustment is not numeric\".into()),\n    }\n    if index < 2 { model.temperature_seen = true; model.tint_seen = true; model.wb_source = raw_core::types::WbSource::Manual; model.wb_scale_version = raw_core::types::WbScaleVersion::default(); }\n    Ok(())\n}\n");
    native.push_str(&setter);
    raster_allowed.push_str("        _ => false,\n    }\n}\n");
    native.push_str(&raster_allowed);
    write(&kotlin.join("AdjustmentFields.kt"), fields)?;
    write(&root.join("src/android/native/src/fields.rs"), native)
}

// Both hosts consume the same display palette; image-pipeline math is unaffected.
fn write_slider_gradients(root: &Path, kotlin: &Path) -> std::io::Result<()> {
    let mut swift = format!("{HEADER}\nextension GradientCatalog {{\n");
    let mut android = format!("{HEADER}package app.justmaple.aperture.generated\n\nimport androidx.compose.ui.graphics.Color\n\nobject SliderGradients {{\n");
    for gradient in raw_core::ui_slider_gradients::SLIDER_GRADIENTS {
        swift.push_str(&format!(
            "  public static let {}: [GradientStop] = [\n",
            gradient.name
        ));
        android.push_str(&format!("    val {} = arrayOf(\n", gradient.name));
        for (position, color) in gradient.stops {
            swift.push_str(&format!(
                "    GradientStop(t: {position:?}, hex: 0x{color:06X}),\n"
            ));
            android.push_str(&format!(
                "        {position:?}f to Color(0xFF{color:06X}),\n"
            ));
        }
        swift.push_str("  ]\n");
        android.push_str("    )\n");
    }
    swift.push_str("}\n");
    android.push_str("}\n");
    write(&root.join("src/apple/Packages/MapleCore/Sources/MapleCore/Generated/GradientCatalog+Generated.swift"), swift)?;
    write(&kotlin.join("SliderGradients.kt"), android)
}

fn write_white_balance_presets(kotlin: &Path) -> std::io::Result<()> {
    let mut body = format!("{HEADER}package app.justmaple.aperture.generated\n\ndata class NamedWhiteBalancePreset(val name: String, val temperature: Float, val tint: Float)\n\nobject WhiteBalancePresets {{\n    val fixed = listOf(\n");
    for preset in raw_core::types::adjustment::WhiteBalancePreset::ALL {
        if let Some((temperature, tint)) = preset.pair() {
            body.push_str(&format!(
                "        NamedWhiteBalancePreset(\"{}\", {temperature:.1}f, {tint:.1}f),\n",
                preset.name()
            ));
        }
    }
    body.push_str("    )\n}\n");
    write(&kotlin.join("WhiteBalancePresets.kt"), body)
}
